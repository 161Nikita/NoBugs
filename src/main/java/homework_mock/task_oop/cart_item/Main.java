package homework_mock.task_oop.cart_item;

/**
 * "В системе есть корзина.
 *
 * У корзины есть:
 * список товаров
 * У каждого товара в корзине есть:
 *
 * название
 * цена
 * количество
 *
 * Нужно реализовать систему, которая может:
 * добавить товар в корзину
 * удалить товар из корзины
 * изменить количество товара
 * посчитать общую стоимость корзины
 * показать содержимое корзины
 *
 * Правила:
 * если количество стало 0, товар удаляется из корзины
 * общая стоимость корзины считается как сумма цена × количество для всех товаров
 *
 * Пример:
 * В корзине:
 *
 * Телефон — 500 × 1
 * Чехол — 20 × 2
 * Зарядка — 30 × 1
 *
 * Общая стоимость:
 * 570"
 */
public class Main {
    public static void main(String[] args) {
        ShoppingCart cart = new ShoppingCart();

        // Сначала создаем базовые продукты (артикулы sku можно передать любые)
        Product phone = new Product("Телефон", 500, "SKU-001");
        Product caseObj = new Product("Чехол", 20, "SKU-002");
        Product charger = new Product("Зарядка", 30, "SKU-003");

        // Добавляем их в корзину по схеме
        cart.addProduct(phone, 1);
        cart.addProduct(caseObj, 2);
        cart.addProduct(charger, 1);

        // Показываем содержимое
        cart.showItems();

        // Выводим общую стоимость
        System.out.println("\nОбщая стоимость:");
        System.out.println((int) cart.calculateTotal());
    }
}
